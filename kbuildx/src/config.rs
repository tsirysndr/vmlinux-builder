use std::fmt::Write as _;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ConfigValue {
    Yes,
    #[allow(dead_code)]
    Module,
    No,
    Decimal(u64),
    Hex(u64),
    String(String),
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ConfigLine {
    Option { name: String, value: ConfigValue },
    Comment(String),
    Blank,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct KernelConfig {
    pub lines: Vec<ConfigLine>,
}

impl KernelConfig {
    #[allow(dead_code)]
    pub fn set(&mut self, name: &str, value: ConfigValue) -> bool {
        if let Some(line) = self.lines.iter_mut().find(
            |line| matches!(line, ConfigLine::Option { name: current, .. } if current == name),
        ) {
            if let ConfigLine::Option { value: current, .. } = line {
                *current = value;
                return true;
            }
        }
        false
    }

    pub fn to_config_text(&self) -> String {
        let mut out = String::new();
        for line in &self.lines {
            match line {
                ConfigLine::Blank => out.push('\n'),
                ConfigLine::Comment(text) => {
                    out.push('#');
                    out.push_str(text);
                    out.push('\n');
                }
                ConfigLine::Option { name, value } => match value {
                    ConfigValue::Yes => {
                        let _ = writeln!(out, "CONFIG_{name}=y");
                    }
                    ConfigValue::Module => {
                        let _ = writeln!(out, "CONFIG_{name}=m");
                    }
                    ConfigValue::No => {
                        let _ = writeln!(out, "# CONFIG_{name} is not set");
                    }
                    ConfigValue::Decimal(value) => {
                        let _ = writeln!(out, "CONFIG_{name}={value}");
                    }
                    ConfigValue::Hex(value) => {
                        let _ = writeln!(out, "CONFIG_{name}={value:#x}");
                    }
                    ConfigValue::String(value) => {
                        let escaped = value.replace('\\', "\\\\").replace('"', "\\\"");
                        let _ = writeln!(out, "CONFIG_{name}=\"{escaped}\"");
                    }
                },
            }
        }
        out
    }
}

impl Default for KernelConfig {
    fn default() -> Self {
        kernel_config()
    }
}

impl ToString for KernelConfig {
    fn to_string(&self) -> String {
        self.to_config_text()
    }
}

fn option(name: &str, value: ConfigValue) -> ConfigLine {
    ConfigLine::Option {
        name: name.to_owned(),
        value,
    }
}

fn comment(text: &str) -> ConfigLine {
    ConfigLine::Comment(text.to_owned())
}

